CREATE TABLE container_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_id UUID NOT NULL REFERENCES server_archives(id),
    event_id UUID NOT NULL,
    payload_hash VARCHAR(64) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    dimension VARCHAR(80) NOT NULL,
    player_key VARCHAR(80),
    player_name VARCHAR(80),
    operation VARCHAR(16) NOT NULL,
    evidence VARCHAR(40) NOT NULL,
    container_type VARCHAR(128) NOT NULL,
    payload TEXT NOT NULL,
    collector_version VARCHAR(64) NOT NULL,
    boot_id UUID NOT NULL,
    UNIQUE(server_id, event_id)
);
CREATE INDEX idx_container_audit_server_time ON container_audit(server_id, occurred_at, id);
CREATE TABLE container_audit_locations (
    audit_id BIGINT NOT NULL REFERENCES container_audit(id) ON DELETE CASCADE,
    server_id UUID NOT NULL,
    dimension VARCHAR(80) NOT NULL,
    x INTEGER NOT NULL,
    y INTEGER NOT NULL,
    z INTEGER NOT NULL,
    PRIMARY KEY(audit_id, x, y, z)
);
CREATE INDEX idx_container_audit_location ON container_audit_locations(server_id, dimension, x, z, y, audit_id);
