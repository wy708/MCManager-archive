CREATE TABLE server_consoles (
    host_id UUID PRIMARY KEY REFERENCES backup_hosts(id) ON DELETE CASCADE,
    run_id UUID NOT NULL,
    heartbeat_at TIMESTAMP WITH TIME ZONE NOT NULL,
    state VARCHAR(20) NOT NULL,
    pid BIGINT
);
CREATE TABLE server_console_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host_id UUID NOT NULL REFERENCES backup_hosts(id) ON DELETE CASCADE,
    run_id UUID NOT NULL,
    sequence BIGINT NOT NULL,
    observed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    line VARCHAR(2000) NOT NULL,
    UNIQUE(host_id, run_id, sequence)
);
CREATE INDEX idx_console_logs_host ON server_console_logs(host_id, id);
CREATE TABLE server_console_commands (
    id UUID PRIMARY KEY,
    host_id UUID NOT NULL REFERENCES backup_hosts(id) ON DELETE CASCADE,
    run_id UUID NOT NULL,
    action VARCHAR(16) NOT NULL,
    command VARCHAR(1000) NOT NULL,
    requested_by VARCHAR(128) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    delivered_at TIMESTAMP WITH TIME ZONE,
    completed_at TIMESTAMP WITH TIME ZONE,
    message VARCHAR(250) NOT NULL DEFAULT ''
);
CREATE INDEX idx_console_commands_host ON server_console_commands(host_id, created_at);
