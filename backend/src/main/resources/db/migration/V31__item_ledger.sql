CREATE TABLE item_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_id UUID NOT NULL REFERENCES server_archives(id) ON DELETE CASCADE,
    event_id UUID NOT NULL,
    payload_hash VARCHAR(64) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    dimension VARCHAR(80) NOT NULL,
    player_key VARCHAR(80), player_name VARCHAR(80),
    operation VARCHAR(32) NOT NULL, evidence VARCHAR(40) NOT NULL,
    entity_ref VARCHAR(80),
    x INTEGER NOT NULL, y INTEGER NOT NULL, z INTEGER NOT NULL,
    payload TEXT NOT NULL,
    collector_version VARCHAR(64) NOT NULL,
    boot_id UUID NOT NULL,
    UNIQUE(server_id,event_id)
);
CREATE INDEX idx_item_ledger_page ON item_ledger(server_id,id DESC);
CREATE INDEX idx_item_ledger_time ON item_ledger(server_id,occurred_at,id);
CREATE INDEX idx_item_ledger_player ON item_ledger(server_id,player_key,occurred_at,id);
CREATE INDEX idx_item_ledger_entity ON item_ledger(server_id,entity_ref,id);
CREATE INDEX idx_item_ledger_area ON item_ledger(server_id,dimension,x,z,y,occurred_at);
CREATE TABLE item_ledger_types (
    ledger_id BIGINT NOT NULL REFERENCES item_ledger(id) ON DELETE CASCADE,
    server_id UUID NOT NULL,
    item_type VARCHAR(128) NOT NULL,
    PRIMARY KEY(ledger_id,item_type)
);
CREATE INDEX idx_item_ledger_types ON item_ledger_types(server_id,item_type,ledger_id);
